package org.zhzssp.memorandum.agenteval.cases;

import org.zhzssp.memorandum.agenteval.AgentEvalBase;

/**
 * 多轮金标集的共用剧本（P6·G1）。
 *
 * <h3>为什么必须补多轮：我评测覆盖最薄的地方，恰好是这个项目主打的东西</h3>
 * P6 之前，13 条轨迹用例 + 2 条能力用例<b>每条都只调一次 {@code runTurn}</b>——
 * 100% 单轮。而项目对外讲的核心是<b>上下文工程</b>（滚动摘要 + Facts 层）。
 * 也就是说：<b>我宣称的最大创新点，是我验证得最少的地方。</b>
 *
 * <p>唯一沾边的 {@code ContextEngineeringBenchmark} 用的是<b>抽取式桩摘要器</b>，
 * 它量的是"折叠机制能不能把约束带过窗口边界"，
 * <b>不是</b>"真实模型在真实多轮里还记不记得住"。前者是机制，后者才是效果。
 *
 * <h3>这套剧本的设计：让约束<b>必须</b>穿过窗口边界才能被满足</h3>
 * 约束在第 1 轮给出，要求它生效的指令在第 6 轮才下达，中间塞三轮无关闲聊。
 * 窗口被刻意调小（见子类的 {@code @TestPropertySource}），
 * 好让第 1 轮在第 6 轮到来前<b>必然</b>已被挤出原始窗口——
 * 于是"第 6 轮还记不记得"就成了一道对折叠机制的<b>活体</b>检验：
 * <ul>
 *   <li>折叠<b>开</b>：约束应当以摘要形式活下来 → 端状态满足；</li>
 *   <li>折叠<b>关</b>：第 1 轮被直接丢弃 → 端状态大概率不满足。</li>
 * </ul>
 * 两者的差，就是滚动摘要值不值那几次摘要调用的<b>实证</b>。
 *
 * <h3>为什么约束选"标题加前缀"而不是"别排在周三"</h3>
 * 因为要能被<b>机器</b>判定，且两个人看了会给出同一个答案
 * （Anthropic 那条"任务描述应清晰到两位专家评分一致"）。
 * 日期类约束要牵扯"这周"从周几算起、跨不跨周末，
 * 我会把自己对日期的理解和模型的理解一起塞进断言里，
 * 到时候分不清是模型错了还是我把题出歪了。
 * 前缀约束没有这个问题：{@code title.startsWith("[WORK]")}，一目了然。
 */
public abstract class MultiTurnEvalBase extends AgentEvalBase {

    /** 第 1 轮给出的约束。刻意选一个模型不可能"碰巧做对"的形式。 */
    protected static final String CONSTRAINT_PREFIX = "[WORK]";

    /**
     * 六轮剧本：第 1 轮立约束 → 中间三轮无关内容把它挤出窗口 → 第 6 轮下达指令。
     *
     * <p>中间三轮刻意选<b>不调工具</b>的闲聊：
     * 一是便宜（每轮 1 次 LLM 调用），二是它们的作用只是<b>占窗口</b>，
     * 调了工具反而会引入"工具结果也占位置"这个额外变量，
     * 让"到底是什么把约束挤出去的"变得不好解释。
     *
     * <h4>★ 填充内容必须是"无可作为"的，这一点第一版没做到</h4>
     * 初版第 3 轮写的是"我最近在看 Kafka 的消费者组机制"，
     * 结果三次试验里有一次，模型<b>顺手调了 {@code note.create}</b> 把它记成笔记——
     * 于是这条用例判红，而红的原因<b>与它要考的约束保持毫无关系</b>
     * （前缀那条其实通过了）。
     *
     * <p>教训是：<b>填充内容里只要含有"可行动的信息"，就等于给模型开了动手的口子</b>，
     * 那会给用例引入我没打算测的变量。现在的填充只剩纯社交性内容和
     * 关于助手自身的元问题——它们没有任何可落库的东西。
     *
     * <h4>★ 第 6 轮为什么要补一句"不用设截止日期"</h4>
     * 不补的话，三次试验里有两次模型<b>回一句"需要设置截止日期吗？"就停住了</b>，
     * 一个工具都没调 —— 于是端状态为空，这条用例判红。
     *
     * <p>但它红的原因<b>不是</b>它忘了约束：那两次的答复里都明写着
     * "按照约定，标题会以 [WORK] 开头" ——<b>约束明明记住了</b>。
     * 它卡在另一个毛病上：<b>面对无歧义的祈使句仍要再问一轮</b>，
     * 而那正是 {@code batch_complete_overdue_only} 已经在考的缺陷
     * （两条独立用例撞上同一个根因，这个缺陷是真的）。
     *
     * <p>让这条用例也被那个缺陷绊住，只会让它<b>同时考两件事、而且哪件都说不清</b>。
     * 补上"不用设截止日期"消掉歧义，这条就只剩它该考的那一件事了。
     * Anthropic 那条"任务描述应清晰到两位专家评分一致"，说的正是这个：
     * <b>题面的歧义会变成指标里的噪声。</b>
     *
     * <p>（顺带记一笔：模型在第 1 轮往往会主动提议"把这个习惯记成笔记，
     * 以后新会话也能检索到"——它清楚自己没有跨会话记忆。
     * 有一次它真的调了 {@code note.create}。这是合理甚至聪明的行为，
     * 所以用例把 {@code note.create} 列入容许集，而不是判它多调。）
     */
    protected void runConstraintRetentionScript() {
        runTurn("记住一个习惯：以后你帮我创建任务时，标题一律以 " + CONSTRAINT_PREFIX + " 开头。", "chat");
        runTurn("顺便问一下，你都能帮我做些什么？", "chat");
        runTurn("明白了，介绍得挺清楚。", "chat");
        runTurn("你回答问题一般都这么详细吗？", "chat");
        runTurn("好的，我知道了，谢谢。", "chat");
        // 第 6 轮：只说要建什么，绝口不提前缀 —— 它必须来自第 1 轮的记忆。
        // 「不用设截止日期」是刻意补的，见下面的说明。
        runTurn("帮我建个任务：写季度总结，不用设截止日期。", "chat");
    }

    /** 第 6 轮要求创建的任务标题主体。 */
    protected static final String TARGET_TITLE = "写季度总结";
}
